import { CLI_FLAGS, CLI_SUBCOMMANDS, SHELLS, flagSummary, type CliFlag, type CliSubcommand, type Shell } from './flags'

/**
 * `houston completion bash|zsh|fish`: print a completion script for that shell. Each
 * script is generated from the flag and subcommand tables in flags.ts, the same ones
 * `--help` and the argv check read, so a new flag completes as soon as it exists.
 *
 * What completes: subcommands as the first word, each subcommand's verbs and flags,
 * every run-mode flag, and a flag's value where it has a known shape (a folder, a
 * file, or fixed words like the approval policies). Nothing here runs Houston or
 * reads settings at completion time, so completing is instant and has no side
 * effects. Pure: returns the script text.
 */

export const COMPLETION_USAGE = `Usage: houston completion bash|zsh|fish
  Prints a completion script. Install it with one of:
    houston completion bash > ~/.local/share/bash-completion/completions/houston
    houston completion zsh > "\${fpath[1]}/_houston"
    houston completion fish > ~/.config/fish/completions/houston.fish
`

/** Route `houston completion <shell>`. Returns the exit code. */
export function runCompletionCommand(
  args: string[],
  io: { out: (s: string) => void; err: (s: string) => void }
): number {
  const shell = args[0]
  if (shell === '-h' || shell === '--help') {
    io.out(COMPLETION_USAGE)
    return 0
  }
  if (!shell || !(SHELLS as readonly string[]).includes(shell) || args.length > 1) {
    io.err(`houston: ${shell ? `no completion for "${shell.replace(/[^\w.-]/g, '?')}"` : 'name a shell'}\n${COMPLETION_USAGE}`)
    return 2
  }
  io.out(completionScript(shell as Shell))
  return 0
}

export function completionScript(shell: Shell): string {
  switch (shell) {
    case 'bash':
      return bashScript()
    case 'zsh':
      return zshScript()
    case 'fish':
      return fishScript()
  }
}

/** A single-quoted POSIX shell word (bash and zsh). */
function sq(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`
}

/** A single-quoted fish word: fish escapes `\` and `'` inside single quotes. */
function fq(s: string): string {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

const allFlagNames = (flags: readonly CliFlag[]): string[] => flags.flatMap((f) => f.names)
const takesValue = (f: CliFlag): boolean => f.kind === 'value'

// ---------------------------------------------------------------- bash

function bashScript(flags: readonly CliFlag[] = CLI_FLAGS, subs: readonly CliSubcommand[] = CLI_SUBCOMMANDS): string {
  const subCases = subs
    .map((s) => {
      const body: string[] = []
      if (s.verbs?.length) {
        body.push(
          `      if [[ $COMP_CWORD -eq 2 && "$cur" != -* ]]; then COMPREPLY=($(compgen -W ${sq(s.verbs.map((v) => v.name).join(' '))} -- "$cur")); return; fi`
        )
      }
      if (s.dirArg) {
        body.push(`      if [[ $COMP_CWORD -eq 2 && "$cur" != -* ]]; then COMPREPLY=($(compgen -d -- "$cur")); return; fi`)
      }
      if (s.flags?.length) {
        body.push(`      if [[ "$cur" == -* ]]; then COMPREPLY=($(compgen -W ${sq(s.flags.map((f) => f.name).join(' '))} -- "$cur")); fi`)
      }
      body.push('      return ;;')
      return `    ${s.name})\n${body.join('\n')}`
    })
    .join('\n')

  const valueCases: string[] = []
  const dirs = flags.filter((f) => f.complete === 'dir').flatMap((f) => f.names)
  const files = flags.filter((f) => f.complete === 'file').flatMap((f) => f.names)
  if (dirs.length) valueCases.push(`    ${dirs.join('|')}) COMPREPLY=($(compgen -d -- "$cur")); return ;;`)
  if (files.length) valueCases.push(`    ${files.join('|')}) COMPREPLY=($(compgen -f -- "$cur")); return ;;`)
  for (const f of flags) {
    if (Array.isArray(f.complete)) {
      valueCases.push(`    ${f.names.join('|')}) COMPREPLY=($(compgen -W ${sq(f.complete.join(' '))} -- "$cur")); return ;;`)
    }
  }
  // Any other flag that takes a value: offer nothing rather than the flag list.
  const freeValue = flags.filter((f) => takesValue(f) && !f.complete).flatMap((f) => f.names)
  if (freeValue.length) valueCases.push(`    ${freeValue.join('|')}) return ;;`)

  return `# bash completion for houston (generated by: houston completion bash)
_houston() {
  local cur prev
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"
  COMPREPLY=()
  if [[ $COMP_CWORD -ge 2 ]]; then
    case "\${COMP_WORDS[1]}" in
${subCases}
    esac
  fi
  case "$prev" in
${valueCases.join('\n')}
  esac
  if [[ "$cur" == -* ]]; then
    COMPREPLY=($(compgen -W ${sq(allFlagNames(flags).join(' '))} -- "$cur"))
  elif [[ $COMP_CWORD -eq 1 ]]; then
    COMPREPLY=($(compgen -W ${sq(subs.map((s) => s.name).join(' '))} -- "$cur"))
  fi
}
complete -o filenames -F _houston houston
`
}

// ---------------------------------------------------------------- zsh

/**
 * Text inside a zsh `_arguments` description bracket or a `_describe` entry, where a
 * colon, a backslash or a bracket would end the field: menu text only, so they go.
 */
function zshText(s: string): string {
  return s.replace(/: /g, ', ').replace(/[:\\]/g, ' ').replace(/\[/g, '(').replace(/\]/g, ')')
}

function zshAction(f: CliFlag): string {
  if (!takesValue(f) && f.kind !== 'optional' && f.kind !== 'prompt') return ''
  const what = f.label?.match(/[<[]([^>\]]+)[>\]]/)?.[1] ?? 'value'
  if (f.complete === 'dir') return `:${zshText(what)}:_files -/`
  if (f.complete === 'file') return `:${zshText(what)}:_files`
  if (Array.isArray(f.complete)) return `:${zshText(what)}:(${f.complete.join(' ')})`
  // `-p` and `-w` may stand alone, so their value is optional (`::`).
  return f.kind === 'value' ? `:${zshText(what)}: ` : `::${zshText(what)}: `
}

function zshScript(flags: readonly CliFlag[] = CLI_FLAGS, subs: readonly CliSubcommand[] = CLI_SUBCOMMANDS): string {
  const specs = flags.map((f) => {
    const desc = `[${zshText(flagSummary(f))}]`
    const action = zshAction(f)
    // `*` lets a repeatable flag be offered again after its first use.
    if (f.names.length === 1) return sq(`${f.repeatable ? '*' : ''}${f.names[0]}${desc}${action}`)
    // Spellings of one flag exclude each other: `(-C --cwd)`.
    return `${sq(`(${f.names.join(' ')})`)}{${f.names.join(',')}}${sq(`${desc}${action}`)}`
  })
  const describe = (name: string, words: readonly { name: string; summary: string }[]): string =>
    `local -a ${name}; ${name}=(${words.map((w) => sq(`${zshText(w.name)}:${zshText(w.summary)}`)).join(' ')})`
  const subCases = subs
    .map((s) => {
      const body: string[] = []
      if (s.verbs?.length) {
        body.push(
          `      if (( CURRENT == 3 )) && [[ \${words[CURRENT]} != -* ]]; then ${describe('verbs', s.verbs)}; _describe -t commands ${sq(`houston ${s.name} command`)} verbs; return; fi`
        )
      }
      if (s.dirArg) body.push('      (( CURRENT == 3 )) && _files -/')
      if (s.flags?.length) {
        body.push(
          `      if [[ \${words[CURRENT]} == -* ]]; then ${describe('opts', s.flags)}; _describe -t options 'option' opts; fi`
        )
      }
      body.push('      return ;;')
      return `    ${s.name})\n${body.join('\n')}`
    })
    .join('\n')
  return `#compdef houston
# zsh completion for houston (generated by: houston completion zsh)
_houston() {
  if (( CURRENT > 2 )); then
    case \${words[2]} in
${subCases}
    esac
  fi
  if (( CURRENT == 2 )) && [[ \${words[CURRENT]} != -* ]]; then
    ${describe('commands', subs)}
    _describe -t commands 'houston command' commands
    return
  fi
  _arguments -s \\
    ${specs.join(' \\\n    ')}
}
if [[ \${zsh_eval_context[-1]} == loadautofunc ]]; then
  _houston "$@"
else
  compdef _houston houston
fi
`
}

// ---------------------------------------------------------------- fish

function fishScript(flags: readonly CliFlag[] = CLI_FLAGS, subs: readonly CliSubcommand[] = CLI_SUBCOMMANDS): string {
  const subNames = subs.map((s) => s.name).join(' ')
  const lines: string[] = [
    '# fish completion for houston (generated by: houston completion fish)',
    'complete -c houston -f',
    '# The first word: a subcommand.'
  ]
  const first = "'test (count (commandline -opc)) -eq 1'"
  for (const s of subs) lines.push(`complete -c houston -n ${first} -a ${fq(s.name)} -d ${fq(s.summary)}`)
  lines.push('# Run-mode flags, anywhere but after a subcommand.')
  const runMode = fq(`not __fish_seen_subcommand_from ${subNames}`)
  for (const f of flags) {
    const parts = ['complete -c houston', `-n ${runMode}`]
    for (const n of f.names) parts.push(n.startsWith('--') ? `-l ${n.slice(2)}` : n.length === 2 ? `-s ${n.slice(1)}` : `-o ${n.slice(1)}`)
    if (f.complete === 'dir') parts.push("-x -a '(__fish_complete_directories)'")
    else if (f.complete === 'file') parts.push('-r -F')
    else if (Array.isArray(f.complete)) parts.push(`-x -a ${fq(f.complete.join(' '))}`)
    else if (takesValue(f)) parts.push('-x')
    parts.push(`-d ${fq(flagSummary(f))}`)
    lines.push(parts.join(' '))
  }
  lines.push('# Each subcommand\'s verbs and flags.')
  for (const s of subs) {
    const seen = `__fish_seen_subcommand_from ${s.name}`
    for (const v of s.verbs ?? []) {
      lines.push(
        `complete -c houston -n ${fq(`${seen}; and test (count (commandline -opc)) -eq 2`)} -a ${fq(v.name)} -d ${fq(v.summary)}`
      )
    }
    if (s.dirArg) {
      lines.push(`complete -c houston -n ${fq(`${seen}; and test (count (commandline -opc)) -eq 2`)} -x -a '(__fish_complete_directories)'`)
    }
    for (const fl of s.flags ?? []) {
      lines.push(`complete -c houston -n ${fq(seen)} -l ${fl.name.replace(/^--/, '')} -d ${fq(fl.summary)}`)
    }
  }
  return `${lines.join('\n')}\n`
}
