// Render the Homebrew formula and the AUR package for one CLI release.
//
// Both install the release's houston-cli.cjs and pin its SHA-256, so they are regenerated
// for every release: the formula from packaging/homebrew/houston.rb.tmpl, the AUR files
// from AUR_FIELDS below.
//
//   node scripts/render-packaging.mjs --version 0.3.0 --sha256 <hex> --out <dir>
//
// writes <dir>/homebrew/houston.rb (for houston-code/homebrew-tap, Formula/houston.rb) and
// <dir>/aur/PKGBUILD + <dir>/aur/.SRCINFO (for the houston-bin AUR repo). .SRCINFO is
// normally made by `makepkg --printsrcinfo`, which needs an Arch host; here both files are
// written from the one AUR_FIELDS list, so their metadata cannot drift apart.
//
// Version and hash are validated strictly before substitution: both land inside Ruby and
// bash source, so nothing but a plain x.y.z and 64 hex digits may reach them.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** A plain x.y.z release version: the only shape any channel publishes. */
export function isReleaseVersion(version) {
  return /^\d+\.\d+\.\d+$/.test(version ?? '')
}

export function validate({ version, sha256 }) {
  // AUR pkgver cannot contain '-', and Houston releases are plain x.y.z anyway.
  if (!isReleaseVersion(version)) throw new Error(`invalid version: ${version}`)
  if (!/^[0-9a-f]{64}$/.test(sha256 ?? '')) throw new Error(`invalid sha256: ${sha256}`)
}

/** Fill {{VERSION}} / {{SHA256}}; any placeholder left over means the template and script drifted. */
export function renderTemplate(template, { version, sha256 }) {
  validate({ version, sha256 })
  const out = template.replaceAll('{{VERSION}}', version).replaceAll('{{SHA256}}', sha256)
  const leftover = out.match(/\{\{[A-Z0-9_]+\}\}/)
  if (leftover) throw new Error(`unfilled placeholder ${leftover[0]}`)
  return out
}

/**
 * The houston-bin metadata, in makepkg's .SRCINFO order. Each entry is [key, value(s)];
 * an array value is a bash array in PKGBUILD and one line per item in .SRCINFO.
 */
function aurFields({ version, sha256 }) {
  return [
    ['pkgdesc', 'Coding agent in your terminal: bring your own model'],
    ['pkgver', version],
    ['pkgrel', '1'],
    ['url', 'https://houstoncode.ai'],
    ['arch', ['any']],
    ['license', ['Apache-2.0']],
    ['depends', ['nodejs>=22']],
    ['provides', ['houston']],
    ['conflicts', ['houston']],
    [
      'source',
      [`houston-cli-${version}.cjs::https://github.com/houston-code/houston/releases/download/v${version}/houston-cli.cjs`],
    ],
    ['sha256sums', [sha256]],
  ]
}

const AUR_PACKAGE = `
package() {
  install -Dm644 "houston-cli-\${pkgver}.cjs" "\${pkgdir}/usr/lib/houston/houston-cli.cjs"
  install -dm755 "\${pkgdir}/usr/bin"
  printf '#!/bin/sh\\nexec /usr/bin/node /usr/lib/houston/houston-cli.cjs "$@"\\n' > "\${pkgdir}/usr/bin/houston"
  chmod 755 "\${pkgdir}/usr/bin/houston"
}
`

/** PKGBUILD for houston-bin. Values are fixed strings plus a validated version and hash. */
export function aurPkgbuild(params) {
  validate(params)
  const quote = (v) => `'${v}'`
  const lines = aurFields(params).map(([key, value]) =>
    Array.isArray(value) ? `${key}=(${value.map(quote).join(' ')})` : `${key}=${quote(value)}`,
  )
  return [
    '# Maintainer: The Houston Authors <dev@houstoncode.ai>',
    '# Generated by scripts/render-packaging.mjs in houston-code/houston. Edit it there, not here.',
    'pkgname=houston-bin',
    ...lines,
  ].join('\n') + '\n' + AUR_PACKAGE
}

/** .SRCINFO for the houston-bin PKGBUILD, from the same fields. */
export function aurSrcinfo(params) {
  validate(params)
  const lines = aurFields(params).flatMap(([key, value]) =>
    (Array.isArray(value) ? value : [value]).map((v) => `\t${key} = ${v}`),
  )
  return ['pkgbase = houston-bin', ...lines, '', 'pkgname = houston-bin', ''].join('\n')
}

export function renderAll(params) {
  const read = (p) => readFileSync(resolve(root, p), 'utf8')
  return {
    'homebrew/houston.rb': renderTemplate(read('packaging/homebrew/houston.rb.tmpl'), params),
    'aur/PKGBUILD': aurPkgbuild(params),
    'aur/.SRCINFO': aurSrcinfo(params),
  }
}

function parseArgs(argv) {
  const opts = {}
  for (let i = 0; i < argv.length; i++) {
    const flag = argv[i]
    if (!['--version', '--sha256', '--out'].includes(flag)) throw new Error(`unknown argument: ${flag}`)
    const value = argv[++i]
    if (!value) throw new Error(`${flag} needs a value`)
    opts[flag.slice(2)] = value
  }
  if (!opts.out) throw new Error('--out is required')
  return opts
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const { version, sha256, out } = parseArgs(process.argv.slice(2))
    for (const [rel, content] of Object.entries(renderAll({ version, sha256 }))) {
      const path = join(resolve(out), rel)
      mkdirSync(dirname(path), { recursive: true })
      writeFileSync(path, content)
      console.log(`wrote ${path}`)
    }
  } catch (err) {
    console.error(`render-packaging: ${err.message}`)
    process.exit(1)
  }
}
